fn glyph(c: char) -> &'static [&'static str; 5] {
    let c = c.to_ascii_lowercase();
    GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, rows)| rows).unwrap_or(&GLYPHS[GLYPHS.len() - 1].1)
}

pub struct TextImage {
    pub w: u32,
    pub h: u32,
    /// sRGB RGBA
    pub px: Vec<u8>,
}

/// Lines of text on a panel, `scale` screen pixels per font pixel.
pub fn render(lines: &[String], scale: u32) -> TextImage {
    let pad = 2;
    let cols = lines.iter().map(|l| l.chars().count()).max().unwrap_or(0) as u32;
    let (cw, ch) = (4, 7);
    let w = (cols * cw + pad * 2 - 1).max(1) * scale;
    let h = (lines.len() as u32 * ch + pad * 2 - 2).max(1) * scale;
    let mut px = vec![0u8; (w * h * 4) as usize];
    let panel = [30, 26, 31, 215];
    for y in 0..h {
        for x in 0..w {
            // Clip the corners for a softer panel.
            let corner = (x < scale || x >= w - scale) && (y < scale || y >= h - scale);
            let i = ((y * w + x) * 4) as usize;
            if !corner {
                px[i..i + 4].copy_from_slice(&panel);
            }
        }
    }
    for (row, line) in lines.iter().enumerate() {
        for (k, c) in line.chars().enumerate() {
            let g = glyph(c);
            for (gy, bits) in g.iter().enumerate() {
                for (gx, b) in bits.bytes().enumerate() {
                    if b != b'1' {
                        continue;
                    }
                    let x0 = (pad + k as u32 * cw + gx as u32) * scale;
                    let y0 = (pad + row as u32 * ch + gy as u32) * scale;
                    for dy in 0..scale {
                        for dx in 0..scale {
                            let i = (((y0 + dy) * w + x0 + dx) * 4) as usize;
                            if i + 4 <= px.len() {
                                px[i..i + 4].copy_from_slice(&[243, 234, 219, 255]);
                            }
                        }
                    }
                }
            }
        }
    }
    TextImage { w, h, px }
}
